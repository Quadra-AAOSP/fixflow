// @vitest-environment jsdom
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { createPinia, setActivePinia } from 'pinia';
import { flushPromises, mount, type VueWrapper } from '@vue/test-utils';
import { nextTick, reactive } from 'vue';
import SubsitesView from '../src/views/app/SubsitesView.vue';
import { useAuthStore } from '../src/stores/auth';
import { useMaintenanceStore } from '../src/stores/maintenance';
import * as api from '../src/services/maintenance';
import { setLocale } from '../src/i18n';
import { site } from './fixtures';
import type { Subsite } from '../src/types/maintenance';
const routing = vi.hoisted(() => ({ params: { siteId: '7' } }));
vi.mock('vue-router', () => ({ useRoute: () => ({ params: reactive(routing.params) }) }));
vi.mock('../src/services/maintenance', () => ({ listSubsites: vi.fn(), listPendingSubsiteRequests: vi.fn(), createSubsite: vi.fn(), updateSubsite: vi.fn(), archiveSubsite: vi.fn(), resolveSubsiteRequest: vi.fn() }));
const building: Subsite = { id: 42, siteId: 7, label: 'A', name: 'Original Main Building', description: null, archivedAt: null };
let wrapper: VueWrapper;
const render = () => mount(SubsitesView, { attachTo: document.body, global: { stubs: { RouterLink: { template: '<a><slot /></a>' } } } });
beforeEach(() => {
  setActivePinia(createPinia()); vi.resetAllMocks(); setLocale('en'); routing.params.siteId = '7';
  useAuthStore().user = { id: 1, role: 'super_admin', siteId: null, firstName: 'Test', lastName: 'Admin', email: 'admin@example.invalid', phone: null, address: null };
  const data = useMaintenanceStore(); data.sites = [site(7), site(8)]; data.selectedSiteId = 7;
  vi.mocked(api.listSubsites).mockResolvedValue([building]); vi.mocked(api.listPendingSubsiteRequests).mockResolvedValue([]);
});
afterEach(() => { wrapper?.unmount(); setLocale('en'); });
describe('labelled building management', () => {
  it('saves a building from Chinese controls and retranslates success without changing its name', async () => {
    setLocale('zh-CN');
    let submitted: unknown;
    vi.mocked(api.createSubsite).mockImplementation(async (siteId, value) => { submitted = { siteId, ...value }; return { ...building, id: 43, label: 'B', name: 'Original Annex' }; });
    wrapper = render(); await flushPromises();
    expect(wrapper.get('h1').text()).toBe('楼宇与地点');
    await wrapper.get('input[maxlength="64"]').setValue('B');
    await wrapper.get('input[maxlength="255"]').setValue('Original Annex');
    await wrapper.get('form').trigger('submit'); await flushPromises();
    expect(submitted).toEqual({ siteId: 7, label: 'B', name: 'Original Annex', description: '' });
    expect(wrapper.text()).toContain('Original Annex');
    expect(wrapper.get('[role="status"]').text()).toContain('已为 Test site 7 保存 B · Original Annex');
    setLocale('en'); await nextTick();
    expect(wrapper.get('[role="status"]').text()).toContain('B · Original Annex saved for Test site 7.');
  });
  it('moves keyboard focus into the editor and returns to the initiating button on cancel', async () => {
    wrapper = render(); await flushPromises();
    const edit = wrapper.get<HTMLButtonElement>('button[aria-label="Edit Original Main Building"]');
    edit.element.focus();
    await edit.trigger('click'); await flushPromises();
    expect(document.activeElement).toBe(wrapper.get('input[maxlength="64"]').element);
    expect(wrapper.get<HTMLInputElement>('input[maxlength="64"]').element.value).toBe('A');
    const cancel = wrapper.findAll('button').find(button => button.text() === 'Cancel editing')!;
    await cancel.trigger('click'); await flushPromises();
    expect(document.activeElement).toBe(edit.element);
    expect(wrapper.get<HTMLInputElement>('input[maxlength="64"]').element.value).toBe('');
    expect(api.updateSubsite).not.toHaveBeenCalled();
  });
  it('focuses the saved confirmation after updating a building', async () => {
    let submitted: unknown;
    vi.mocked(api.updateSubsite).mockImplementation(async (siteId, id, value) => {
      submitted = { siteId, id, ...value };
      return { ...building, name: 'Updated Building' };
    });
    wrapper = render(); await flushPromises();
    await wrapper.get('button[aria-label="Edit Original Main Building"]').trigger('click');
    await wrapper.get('input[maxlength="255"]').setValue('Updated Building');
    await wrapper.get('form').trigger('submit'); await flushPromises();
    expect(submitted).toEqual({ siteId: 7, id: 42, label: 'A', name: 'Updated Building', description: '' });
    expect(document.activeElement).toBe(wrapper.get('[role="status"]').element);
    expect(wrapper.get('[role="status"]').text()).toContain('Updated Building saved');
  });
  it('retains the editor and entered values after a rejected update', async () => {
    vi.mocked(api.updateSubsite).mockRejectedValue(new Error('Building label already exists'));
    wrapper = render(); await flushPromises();
    await wrapper.get('button[aria-label="Edit Original Main Building"]').trigger('click');
    await wrapper.get('input[maxlength="255"]').setValue('Retry Building');
    await wrapper.get('form').trigger('submit'); await flushPromises();
    expect(wrapper.get('[role="alert"]').text()).toContain('Building label already exists');
    expect(wrapper.get<HTMLInputElement>('input[maxlength="255"]').element.value).toBe('Retry Building');
    expect(wrapper.get('fieldset').attributes('disabled')).toBeUndefined();
    expect(wrapper.text()).toContain('Cancel editing');
    expect(wrapper.find('[role="status"]').exists()).toBe(false);
    expect(wrapper.text()).toContain('Original Main Building');
  });
  it('does not move focus when an old site save completes after switching sites', async () => {
    let finish!: (row: Subsite) => void;
    vi.mocked(api.updateSubsite).mockImplementation(() => new Promise(resolve => { finish = resolve; }));
    wrapper = render(); await flushPromises();
    await wrapper.get('button[aria-label="Edit Original Main Building"]').trigger('click');
    await wrapper.get('form').trigger('submit');
    reactive(routing.params).siteId = '8'; await flushPromises();
    const back = wrapper.get<HTMLAnchorElement>('a');
    back.element.setAttribute('href', '/sites'); back.element.focus();
    finish({ ...building, name: 'Old site result' }); await flushPromises();
    expect(document.activeElement).toBe(back.element);
    expect(wrapper.find('[role="status"]').exists()).toBe(false);
    expect(wrapper.text()).not.toContain('Old site result');
  });
  it('does not show zero pending requests after a request-list failure', async () => {
    vi.mocked(api.listPendingSubsiteRequests).mockRejectedValue(new Error('Request list unavailable'));
    wrapper = render(); await flushPromises();
    expect(wrapper.text()).toContain('Request list unavailable');
    expect(wrapper.text()).not.toContain('0 pending');
    expect(wrapper.text()).not.toContain('No pending building requests.');
  });
  it('never adds a late save to a different site or after leaving and returning to the same site', async () => {
    let finish!: (row: Subsite) => void;
    vi.mocked(api.createSubsite).mockImplementation(() => new Promise(resolve => { finish = resolve; }));
    wrapper = render(); await flushPromises();
    await wrapper.get('input[maxlength="64"]').setValue('B');
    await wrapper.get('input[maxlength="255"]').setValue('Late Annex');
    await wrapper.get('form').trigger('submit');
    reactive(routing.params).siteId = '8'; await flushPromises();
    reactive(routing.params).siteId = '7'; await flushPromises();
    finish({ ...building, id: 43, name: 'Late Annex' }); await flushPromises();
    expect(wrapper.text()).not.toContain('Late Annex');
    expect(wrapper.find('[role="status"]').exists()).toBe(false);
  });
  it('shows buildings to reporters without management controls or private requests', async () => {
    useAuthStore().user!.role = 'reporter'; useAuthStore().user!.siteId = 7;
    wrapper = render(); await flushPromises();
    expect(wrapper.text()).toContain('Original Main Building');
    expect(wrapper.find('form').exists()).toBe(false);
    expect(api.listPendingSubsiteRequests).not.toHaveBeenCalled();
    expect(wrapper.find('button[aria-label="Archive Original Main Building"]').exists()).toBe(false);
  });
});
it('accepts a suggested building and closes its request only after the building is saved', async () => {
  vi.mocked(api.listPendingSubsiteRequests).mockResolvedValue([{ id: 9, siteId: 7, requestedByUserId: 4, note: 'New library', status: 'pending', createdAt: '2026-11-09T08:00:00Z' }]);
  let submitted: unknown;
  vi.mocked(api.createSubsite).mockImplementation(async (siteId, form) => { submitted = { siteId, ...form }; return { ...building, id: 50, label: 'LIB', name: 'New library' }; });
  vi.mocked(api.resolveSubsiteRequest).mockResolvedValue(undefined);
  wrapper = render(); await flushPromises();
  await wrapper.findAll('button').find(button => button.text() === 'Accept suggestion')!.trigger('click');
  expect(api.resolveSubsiteRequest).not.toHaveBeenCalled();
  expect(wrapper.get<HTMLInputElement>('input[maxlength="255"]').element.value).toBe('New library');
  await wrapper.get('input[maxlength="64"]').setValue('LIB');
  await wrapper.get('form').trigger('submit'); await flushPromises();
  expect(submitted).toEqual(expect.objectContaining({ siteId: 7, label: 'LIB', name: 'New library' }));
  expect(api.resolveSubsiteRequest).toHaveBeenCalledWith(7, 9);
  expect(wrapper.text()).not.toContain('Accept suggestion');
});
it('requires a deliberate confirmation before archiving and supports cancellation', async () => {
  vi.mocked(api.archiveSubsite).mockResolvedValue(undefined);
  wrapper = render(); await flushPromises();
  const archive = wrapper.get('button[aria-label="Archive Original Main Building"]');
  await archive.trigger('click');
  expect(api.archiveSubsite).not.toHaveBeenCalled();
  const confirmation = wrapper.get('.archive-confirmation');
  expect(confirmation.text()).toContain('no longer be available for new reports');
  await confirmation.findAll('button').find(button => button.text() === 'Cancel')!.trigger('click');
  expect(wrapper.find('.archive-confirmation').exists()).toBe(false);
  expect(api.archiveSubsite).not.toHaveBeenCalled();
  await archive.trigger('click');
  await wrapper.get('.archive-confirmation').findAll('button').find(button => button.text() === 'Confirm archive')!.trigger('click');
  await flushPromises();
  expect(api.archiveSubsite).toHaveBeenCalledWith(7, 42);
  expect(wrapper.find('button[aria-label="Archive Original Main Building"]').exists()).toBe(false);
});
